#!/usr/bin/env python3
"""Write the pipeline's SPARQL files from entries/entries.json.

    python3 tools/make_pipeline.py           write pipeline/*.rq
    python3 tools/make_pipeline.py --check   exit 1 if pipeline/*.rq differ from what
                                             the entries file now gives

Every file in pipeline/ is generated; none is edited by hand. Each is plain
SPARQL 1.1 (Query or Update) over four named graphs:

    :asserted          the input, Skolemized
    :closure           what the regime's rules add to :asserted
    :defaults          the conclusions of the default entries that apply
    :default-closure   what the regime's rules add once :defaults is included

K is :asserted with :closure; Cons is all four. Standard library only.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "entries" / "entries.json"
OUT = ROOT / "pipeline"
GRAPHS = "https://github.com/bradleypallen/iss-rdf-wikidata/graph/"
K = [":asserted", ":closure"]
CONS = [":asserted", ":closure", ":defaults", ":default-closure"]
BOT = "BOT"
HEADER = "# Generated by tools/make_pipeline.py from entries/entries.json. Do not edit.\n"


def is_var(term):
    return term.startswith("?")


def renamer(suffix):
    return lambda term: term + suffix if is_var(term) else term


def same(term):
    return term


def pattern(triples, rename=same, indent="    "):
    return "".join(f"{indent}{' '.join(rename(t) for t in triple)} .\n" for triple in triples)


def body(item, rename=same, defeaters="absent"):
    """The WHERE lines of one rule or entry: expansions, premises, guards, defeaters."""
    text = ""
    for var, values in item.get("expand", {}).items():
        text += f"    VALUES {rename(var)} {{ {' '.join(values)} }}\n"
    text += pattern(item["premises"], rename)
    for guard in item.get("guards", []):
        text += f"    FILTER({rename(guard['left'])} {guard['op']} {rename(guard['right'])})\n"
    if defeaters == "absent":
        for defeater in item.get("defeaters", []):
            text += "    FILTER NOT EXISTS {\n" + pattern(defeater, rename, "      ") + "    }\n"
    return text


def variables(item, with_defeaters=False):
    triples = list(item["premises"])
    if with_defeaters:
        for defeater in item.get("defeaters", []):
            triples += defeater
    found = []
    for triple in triples:
        for term in triple:
            if is_var(term) and term not in found:
                found.append(term)
    return found


def prefixes(doc):
    lines = [f"PREFIX {name}: <{iri}>" for name, iri in doc["prefixes"].items()]
    return "\n".join(lines + [f"PREFIX : <{GRAPHS}>"]) + "\n\n"


def dataset(graphs, word):
    return "".join(f"{word} {g}\n" for g in graphs)


def materialize(doc, target, graphs, title):
    updates = []
    for rule in doc["regime"]["rules"]:
        updates.append(
            f"# rule {rule['id']}\n"
            f"INSERT {{ GRAPH {target} {{ {' '.join(rule['conclusion'])} }} }}\n"
            + dataset(graphs, "USING") + "WHERE {\n" + body(rule)
            + f"    FILTER NOT EXISTS {{ {' '.join(rule['conclusion'])} }}\n}}")
    return (HEADER + f"# {title}\n# Repeated until it adds nothing. Each rule adds only triples that none of the\n"
            "# graphs it reads holds yet, so the named graphs do not repeat one another.\n\n"
            + prefixes(doc) + " ;\n\n".join(updates) + "\n")


def defaults_construct(doc):
    template, branches = "", []
    for number, entry in enumerate(e for e in doc["entries"] if e["kind"] == "default"):
        rename = renamer(f"_{number + 1}")
        template += f"  {' '.join(rename(t) for t in entry['conclusion'])} .\n"
        branches.append(f"  {{ # entry {entry['id']}\n" + body(entry, rename) + "  }")
    return (HEADER + "# Step 2. One round of the default entries against K (:asserted with :closure).\n"
            "# The result is loaded into :defaults. Variables are numbered by entry.\n\n"
            + prefixes(doc) + "CONSTRUCT {\n" + template + "}\n" + dataset(K, "FROM")
            + "WHERE {\n" + "\n  UNION\n".join(branches) + "\n}\n")


def select(doc, title, branches, columns, graphs):
    order = " ".join(columns)
    return (HEADER + f"# {title}\n\n" + prefixes(doc) + f"SELECT DISTINCT {order}\n" + dataset(graphs, "FROM")
            + "WHERE {\n" + "\n  UNION\n".join(branches) + f"\n}}\nORDER BY {order}\n")


def columns_of(entries, with_defeaters=False):
    found = ["?entry"]
    for entry in entries:
        for var in variables(entry, with_defeaters):
            if var not in found:
                found.append(var)
    return found


def default_instances(doc):
    entries = [e for e in doc["entries"] if e["kind"] == "default"]
    branches = [f"  {{ # entry {e['id']}\n    BIND(\"{e['id']}\" AS ?entry)\n" + body(e) + "  }" for e in entries]
    return select(doc, "Step 2, for the report. The instances of default entries that apply at K.",
                  branches, columns_of(entries), K)


def defeated(doc):
    entries = [e for e in doc["entries"] if e["kind"] == "default" and e.get("defeaters")]
    branches = []
    for entry in entries:
        for number, defeater in enumerate(entry["defeaters"]):
            branches.append(
                f"  {{ # entry {entry['id']}, defeater {number + 1}\n"
                f"    BIND(\"{entry['id']}\" AS ?entry)\n    BIND({number + 1} AS ?defeater)\n"
                + body(entry, defeaters="ignored") + pattern(defeater) + "  }")
    columns = columns_of(entries, with_defeaters=True)
    columns.insert(1, "?defeater")
    return select(doc, "Step 2, for the report. Default instances whose premises are in K and which a\n"
                       "# defeater instance in K defeats, with the defeater's bindings.",
                  branches, columns, K)


def incompatibilities(doc, graphs, title):
    entries = [e for e in doc["entries"] if e["kind"] == "incompatibility"]
    branches = [f"  {{ # entry {e['id']}\n    BIND(\"{e['id']}\" AS ?entry)\n" + body(e) + "  }" for e in entries]
    return select(doc, title, branches, columns_of(entries), graphs)


def spouse_of(doc, graphs, title):
    return (HEADER + f"# {title}\n\n" + prefixes(doc) + "SELECT DISTINCT ?who ?spouse\n" + dataset(graphs, "FROM")
            + "WHERE {\n    ?who wdt:P26 ?spouse .\n}\nORDER BY ?spouse ?who\n")


def files(doc):
    return {
        "1-closure.rq": materialize(doc, ":closure", K, "Step 1. Materialize the regime over :asserted into :closure."),
        "2-defaults.rq": defaults_construct(doc),
        "2-default-instances.rq": default_instances(doc),
        "2-defeated.rq": defeated(doc),
        "2-incompatibilities.rq": incompatibilities(
            doc, K, "Step 2. The incompatibility entries that apply at K (:asserted with :closure)."),
        "3-default-closure.rq": materialize(
            doc, ":default-closure", CONS, "Step 3. Materialize the regime over K with :defaults into :default-closure."),
        "4-recheck.rq": incompatibilities(
            doc, CONS, "Step 4. The incompatibility entries that apply over Cons (all four graphs).\n"
                       "# Premises and defeaters are both read in Cons."),
        "q-spouse-of-at-closure.rq": spouse_of(doc, K, "Who has whom as spouse, over K."),
        "q-spouse-of-at-cons.rq": spouse_of(doc, CONS, "Who has whom as spouse, over Cons."),
    }


def main():
    doc = json.loads(ENTRIES.read_text(encoding="utf-8"))
    generated = files(doc)
    if "--check" in sys.argv:
        stale = [name for name, text in generated.items()
                 if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf-8") != text]
        extra = [p.name for p in OUT.glob("*.rq") if p.name not in generated]
        for name in stale:
            print("stale  ", name)
        for name in extra:
            print("extra  ", name)
        print(f"{len(generated)} files, {len(stale)} stale, {len(extra)} not generated")
        sys.exit(1 if stale or extra else 0)
    OUT.mkdir(exist_ok=True)
    for name, text in generated.items():
        (OUT / name).write_text(text, encoding="utf-8")
        print("wrote  ", f"pipeline/{name}")


if __name__ == "__main__":
    main()
