#!/usr/bin/env python3
"""Look into two kinds of disagreement between the entries and the checker.

    python3 tools/calibration_followup.py queries results/pipeline/full-p26/<timestamp>
        writes queries/calibration-followup-*.rq (generated; small, several of them,
        because the endpoint refuses a long query):
          reverse     for sampled triples x spouse y where the entries expect a symmetric
                      violation and the checker reports none: is there a statement
                      y spouse x at any rank, and is y a redirect?
          precision   for the sampled contemporary statements: the birth and death
                      dates of both parties with their precision

    python3 tools/calibration_followup.py summary results/pipeline/full-p26/<timestamp>
        reads the latest results of those queries and writes calibration-followup.json
        and calibration-followup.md into the run directory

Standard library only.
"""
import collections
import json
import pathlib
import sys

from calibration_table import REPORTED, responses

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAMPLE = ROOT / "data" / "full-p26" / "calibration-sample.json"
SYMMETRIC, CONTEMPORARY = "Q21510862", "Q25796498"
DATED = ["conflict-contemporary", "contemporary-no-1-january", "contemporary-1-january"]
PRECISION = {11: "day", 10: "month", 9: "year", 8: "decade", 7: "century", 6: "millennium"}
PREFIXES = """PREFIX p: <http://www.wikidata.org/prop/>
PREFIX ps: <http://www.wikidata.org/prop/statement/>
PREFIX psv: <http://www.wikidata.org/prop/statement/value/>
PREFIX wikibase: <http://wikiba.se/ontology#>
PREFIX owl: <http://www.w3.org/2002/07/owl#>
"""


def checked(doc):
    """(category, item, statement, constraint types the checker reports) for every sampled statement."""
    for number, (name, category) in enumerate(doc["categories"].items(), 1):
        answers = responses(ROOT / "results", number, name)
        for item in category["items"]:
            for statement in item["statements"]:
                checks = answers.get(statement["claim"].lower())
                if checks is not None:
                    yield name, item, statement, {c["constraint"]["type"] for c in checks if c["status"] in REPORTED}


def latest(pattern):
    rows = []
    for directory in sorted((ROOT / "results").glob(pattern)):
        bodies = [p for p in sorted(directory.glob("*.json")) if not p.name.endswith(".meta.json")]
        if bodies:
            rows += json.loads(bodies[-1].read_text(encoding="utf-8"))["results"]["bindings"]
    return rows


def write_queries():
    doc = json.loads(SAMPLE.read_text(encoding="utf-8"))
    pairs, parties = set(), set()
    for name, item, _, reported in checked(doc):
        if name != "unknown-value" and SYMMETRIC in item["expected"] and SYMMETRIC not in reported:
            pairs.add((item["x"], item["y"]))
        if name in DATED:
            parties |= {item["x"], item["y"]}
    header = "# Generated by tools/calibration_followup.py. Do not edit.\n"
    values = "\n".join(f"    ({x} {y})" for x, y in sorted(pairs))
    (ROOT / "queries" / "calibration-followup-reverse.rq").write_text(header + f"""# Sampled spouse triples x spouse y for which the entries expect a symmetric
# violation and the checker reports none: any statement y spouse x, at any
# rank, and whether y is a redirect (and if so, whether its target has one).
{PREFIXES}
SELECT ?x ?y ?reverse ?rank ?target ?targetReverse WHERE {{
  VALUES (?x ?y) {{
{values}
  }}
  OPTIONAL {{ ?y p:P26 ?reverse . ?reverse ps:P26 ?x . ?reverse wikibase:rank ?rank }}
  OPTIONAL {{ ?y owl:sameAs ?target . OPTIONAL {{ ?target p:P26 ?targetReverse . ?targetReverse ps:P26 ?x }} }}
}}
""", encoding="utf-8")
    ordered = sorted(parties)
    for number, start in enumerate(range(0, len(ordered), 40), 1):
        chunk = "\n".join(f"    {p}" for p in ordered[start:start + 40])
        (ROOT / "queries" / f"calibration-followup-precision-{number:02d}.rq").write_text(header + f"""# Birth and death dates, with precision and rank, of the parties of the
# sampled contemporary statements (part {number}). Precision 11 is a day, 10 a
# month, 9 a year, 8 a decade, 7 a century.
{PREFIXES}
SELECT ?party ?kind ?time ?precision ?rank WHERE {{
  VALUES ?party {{
{chunk}
  }}
  {{ ?party p:P569 ?statement . ?statement psv:P569 ?value . BIND("birth" AS ?kind) }}
  UNION
  {{ ?party p:P570 ?statement . ?statement psv:P570 ?value . BIND("death" AS ?kind) }}
  ?value wikibase:timeValue ?time .
  ?value wikibase:timePrecision ?precision .
  ?statement wikibase:rank ?rank .
}}
""", encoding="utf-8")
    print(f"{len(pairs)} triples for the reverse query; {len(ordered)} parties in "
          f"{(len(ordered) + 39) // 40} precision queries")


def summary(run):
    doc = json.loads(SAMPLE.read_text(encoding="utf-8"))

    # Symmetric expected, not reported.
    reverse = collections.defaultdict(lambda: {"ranks": set(), "redirect": False, "target_has_reverse": False})
    for b in latest("calibration-followup-reverse"):
        entry = reverse[(f"<{b['x']['value']}>", f"<{b['y']['value']}>")]
        if "rank" in b:
            entry["ranks"].add(b["rank"]["value"].rsplit("#", 1)[1])
        entry["redirect"] |= "target" in b
        entry["target_has_reverse"] |= "targetReverse" in b
    reasons = collections.Counter()
    for pair, found in sorted(reverse.items()):
        if found["ranks"]:
            reasons["a statement y spouse x exists, not at best rank (" + ", ".join(sorted(found["ranks"])) + ")"] += 1
        elif found["target_has_reverse"]:
            reasons["y is a redirect, and its target has the reverse statement"] += 1
        elif found["redirect"]:
            reasons["y is a redirect; its target has no reverse statement"] += 1
        else:
            reasons["no reverse statement found at any rank"] += 1

    # Contemporary: precision of the dates the entry compared, against whether the checker reports it.
    precision = collections.defaultdict(dict)   # party -> (kind, lexical date) -> coarsest precision recorded
    for b in latest("calibration-followup-precision-*"):
        key = (b["kind"]["value"], b["time"]["value"])
        table = precision[f"<{b['party']['value']}>"]
        table[key] = min(table.get(key, 99), int(b["precision"]["value"]))
    rows = json.loads((run / "4-recheck.json").read_text(encoding="utf-8"))
    compared = collections.defaultdict(set)      # unordered party pair -> (end party, end, start party, start)
    for row in rows:
        if row["entry"].startswith("p26-contemporary"):
            end_party, start_party = (row["x"], row["y"]) if row["entry"].endswith("subject-first") else (row["y"], row["x"])
            compared[frozenset((row["x"], row["y"]))].add((end_party, row["end"], start_party, row["start"]))
    lexical = lambda literal: literal.split('"')[1]
    cross = collections.defaultdict(collections.Counter)
    for name, item, _, reported in checked(doc):
        if name not in DATED:
            continue
        found = []
        for end_party, end, start_party, start in compared[frozenset((item["x"], item["y"]))]:
            found.append(min(precision[end_party].get(("death", lexical(end)), -1),
                             precision[start_party].get(("birth", lexical(start)), -1)))
        if not found or min(found) < 0:
            kind = "precision not found"
        elif max(found) == 11:
            kind = "some compared pair of dates is exact to the day"
        else:
            kind = "every compared pair has a date coarser than a day (" + PRECISION.get(max(found), str(max(found))) + " at best)"
        cross[kind]["checker reports contemporary" if CONTEMPORARY in reported else "checker does not"] += 1

    out = {"symmetric expected, not reported": dict(reasons),
           "contemporary by precision": {k: dict(v) for k, v in sorted(cross.items())}}
    (run / "calibration-followup.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    lines = ["| Symmetric violation expected by the entries, none reported | Statements |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(reasons.items())]
    lines += ["", "| Dates the contemporary entry compared | Checker reports contemporary | Checker does not |", "|---|---:|---:|"]
    lines += [f"| {k} | {v.get('checker reports contemporary', 0)} | {v.get('checker does not', 0)} |"
              for k, v in sorted(cross.items())]
    (run / "calibration-followup.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "queries":
        write_queries()
    elif len(sys.argv) == 3 and sys.argv[1] == "summary":
        summary(pathlib.Path(sys.argv[2]))
    else:
        sys.exit(__doc__)
